#!/usr/bin/env python3
"""Remove the per-user OS integration a full uninstall would otherwise leave.

Shortcuts and the tray autostart entry are owned by
``scripts/install_desktop_shortcuts.py`` and ``scripts/uninstall_apps.py``.
Everything else the suite writes outside its install tree lives here:

  * Linux icons, the ``mp-desktop-exec`` helper and the ``launcher`` stubs
  * ``systemd --user`` units (Web Companion, bit-rot scrub timer, boot ledger)
  * macOS LaunchAgents and the app bundles they point at
  * the Windows ``Startup`` entry for the Web Companion
  * KDE window rules the player and console add to ``kwinrulesrc``
  * the dynamic-MOTD hook in ``~/.bashrc``

A reset never calls any of this: it runs only when the last MP application is
uninstalled. Nothing here touches music, mixes, playlists, favorites, backups,
exports or the install tree. Every step is best effort; a missing file or a
command that is not installed is skipped, not an error.
"""

from __future__ import annotations

import configparser
import os
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Callable, Iterable, Sequence

# Services the suite installs for itself. The Harmony Agent is a separate
# project with its own installer, so its unit is deliberately not listed.
SYSTEMD_UNITS = (
    "mp-web-companion.service",
    "mix-archive-scrub.timer",
    "mix-archive-scrub.service",
    "mp-boot-death-ledger.service",
)

# macOS login agents. The tray and companion are ours; the archive mount agent
# is an opt-in part of this tree (scripts/mount_mix_archives.sh --install).
LAUNCHD_LABELS = (
    "com.mplanetarian.mp-mix-manager-tray",
    "com.mplanetarian.mp-web-companion",
    "com.mplanetarian.mp-mix-archives",
)

# Files under ~/.local/share that the installer writes and never revisits.
ICON_GLOBS = (
    ".local/share/icons/hicolor/*/apps/mp_liquid_glass_icon.*",
    ".local/share/icons/mp_liquid_glass_icon.*",
)

# Integration that lives inside the config directory but is not a setting.
CONFIG_INTEGRATION_PATHS = (
    "MP Mix Manager Tray.app",
    "launchers",
)

# Generated by install_desktop_shortcuts.py so the .desktop entries can find
# this tree after it moves. Only a link into that tree is removed.
DESKTOP_HELPER = Path(".local") / "bin" / "mp-desktop-exec"

# Windows has no per-user service host, so the companion is a Startup shortcut.
WINDOWS_STARTUP_FILES = ("MP Web Companion.lnk",)

# KDE window rules the console and the player add. They are keyed by their
# human description, which is what the writers match on.
KDE_RULE_DESCRIPTIONS = (
    "Mix Tracklist Viewer (Borderless)",
    "Mix Cover Art Viewer (Keep Above)",
    "MP Mini Audio Player (Fixed Size)",
    "MP Micro Audio Player (Fixed Size)",
    "MP Vertical Audio Player (Fixed Size)",
)

MOTD_BEGIN = "# >>> MP Mix Archive Manager Dynamic MOTD >>>"
MOTD_END = "# <<< MP Mix Archive Manager Dynamic MOTD <<<"

COMPANION_BUNDLE_ID = "com.mplanetarian.mp-web-companion"

# Live processes that would rewrite state files while they are being deleted.
PROCESS_PATTERNS = (
    "mp_system_tray\\.py",
    "windows_tray\\.ps1",
    "MP_Liquid_Mixer\\.py",
    "black_glass_window\\.py",
    "schedule_mix_playback\\.py",
    "mp_visualizer_idle_saver",
    "mix_web_companion\\.py",
)

# bundle id -> candidate locations. The legacy in-tree copy is included so an
# upgrade from an older build does not leave two bundles resolving at once.
MAC_BUNDLES = (
    Path("/Applications/MP Web Companion.app"),
    Path("~/Applications/MP Web Companion.app"),
)

Printer = Callable[[str], None]
Runner = Callable[[Sequence[str]], None]


def _noop_runner(_argv: Sequence[str]) -> None:
    return None


def _default_runner(argv: Sequence[str]) -> None:
    """Run a helper that exists on this host; never fail the uninstall."""
    if not argv or shutil.which(str(argv[0])) is None:
        return
    try:
        subprocess.run(
            [str(part) for part in argv],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            timeout=15,
            check=False,
        )
    except (OSError, subprocess.SubprocessError):
        return


def _say(printer: Printer, text: str) -> None:
    printer(text)


def _remove_tree(path: Path) -> None:
    try:
        if path.is_symlink() or path.is_file():
            path.unlink()
        elif path.is_dir():
            shutil.rmtree(path)
    except OSError:
        return


def _remove_path(path: Path, printer: Printer, label: str, dry_run: bool) -> bool:
    if not os.path.lexists(path):
        return False
    if dry_run:
        _say(printer, f"Would remove {label}: {path}")
        return True
    _remove_tree(path)
    _say(printer, f"Removed {label}: {path}")
    return not os.path.lexists(path)


def _bundle_identifier(bundle: Path) -> str:
    info = bundle / "Contents" / "Info.plist"
    try:
        text = info.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""
    marker = "CFBundleIdentifier"
    index = text.find(marker)
    if index < 0:
        return ""
    start = text.find("<string>", index)
    end = text.find("</string>", start)
    if start < 0 or end < 0:
        return ""
    return text[start + len("<string>") : end].strip()


def _lsregister() -> Path:
    return Path(
        "/System/Library/Frameworks/CoreServices.framework"
        "/Frameworks/LaunchServices.framework/Support/lsregister"
    )


def remove_services(
    home: Path,
    *,
    dry_run: bool,
    printer: Printer = print,
    runner: Runner | None = None,
) -> None:
    """Stop and delete the suite's background units and login agents."""
    run = runner or _default_runner
    systemd_dir = home / ".config" / "systemd" / "user"
    for unit in SYSTEMD_UNITS:
        unit_path = systemd_dir / unit
        if not os.path.lexists(unit_path):
            continue
        if dry_run:
            _say(printer, f"Would stop and remove service: {unit}")
            continue
        run(["systemctl", "--user", "disable", "--now", unit])
        _remove_path(unit_path, printer, "service", dry_run)
    if not dry_run and systemd_dir.is_dir():
        run(["systemctl", "--user", "daemon-reload"])

    agents = home / "Library" / "LaunchAgents"
    for label in LAUNCHD_LABELS:
        plist = agents / f"{label}.plist"
        if not os.path.lexists(plist):
            continue
        if dry_run:
            _say(printer, f"Would unload and remove login agent: {label}")
            continue
        run(["launchctl", "bootout", f"gui/{os.getuid()}/{label}"])
        _remove_path(plist, printer, "login agent", dry_run)

    # This module owns the companion service, so it also stops the process that
    # unit was running. The other apps are stopped by the caller, which knows
    # whether --no-stop was passed.
    stop_companion(dry_run=dry_run, printer=printer, runner=run)


def stop_processes(
    *,
    dry_run: bool,
    printer: Printer = print,
    runner: Runner | None = None,
) -> None:
    """Stop the tray, mixer, companion and schedulers before their state goes."""
    run = runner or _default_runner
    if shutil.which("pkill") is None:
        return
    for pattern in PROCESS_PATTERNS:
        if dry_run:
            _say(printer, f"Would stop process matching: {pattern}")
            continue
        run(["pkill", "-f", pattern])


def stop_companion(
    *, dry_run: bool, printer: Printer = print, runner: Runner | None = None
) -> None:
    """Stop the Web Companion, which its own service unit started."""
    run = runner or _default_runner
    if shutil.which("pkill") is None:
        return
    if dry_run:
        _say(printer, "Would stop the MP Web Companion")
        return
    run(["pkill", "-f", "mix_web_companion\\.py"])


def remove_icons(home: Path, *, dry_run: bool, printer: Printer = print) -> None:
    """Delete the hicolor icon set the shortcuts reference by name."""
    icons_root = home / ".local" / "share" / "icons"
    removed_any = False
    for pattern in ICON_GLOBS:
        for path in sorted(home.glob(pattern)):
            if _remove_path(path, printer, "icon", dry_run):
                removed_any = True
    if removed_any and not dry_run:
        runner = _default_runner
        runner(["gtk-update-icon-cache", "-f", "-t", str(icons_root / "hicolor")])
    elif icons_root.is_dir() and not dry_run and any(
        (icons_root / "hicolor").glob("*/apps/mp_liquid_glass_icon.*")
    ):
        _default_runner(["gtk-update-icon-cache", "-f", "-t", str(icons_root / "hicolor")])


def remove_desktop_helper(
    home: Path,
    root: Path,
    *,
    dry_run: bool,
    printer: Printer = print,
) -> None:
    """Unlink only a helper link that points into this install tree.

    A real file at that path may belong to the user or to a package, and a link
    into some other tree must keep working, so neither is touched.
    """
    link = home / DESKTOP_HELPER
    if not os.path.lexists(link) or not link.is_symlink():
        return
    try:
        target = link.resolve()
    except OSError:
        target = Path("")
    try:
        target.relative_to(root.resolve())
        mine = True
    except (OSError, ValueError):
        mine = False
    # A dangling link is one of ours unless it points somewhere explicit.
    if not mine and os.path.exists(link):
        _say(printer, f"Kept desktop helper (not this install): {link}")
        return
    _remove_path(link, printer, "desktop helper", dry_run)


def remove_kwin_rules(
    home: Path,
    *,
    dry_run: bool,
    printer: Printer = print,
    runner: Runner | None = None,
) -> None:
    """Drop the borderless/fixed-size window rules this suite added to KWin."""
    run = runner or _default_runner
    rc_path = home / ".config" / "kwinrulesrc"
    if not rc_path.is_file():
        return
    parser = configparser.ConfigParser(interpolation=None, strict=False)
    try:
        parser.read(rc_path, encoding="utf-8")
    except (OSError, configparser.Error):
        return

    doomed = [
        section
        for section in parser.sections()
        if parser.has_option(section, "description")
        and parser.get(section, "description") in KDE_RULE_DESCRIPTIONS
    ]
    if not doomed:
        return
    if dry_run:
        for section in doomed:
            _say(printer, f"Would remove KDE window rule: {parser.get(section, 'description')}")
        return

    for section in doomed:
        description = parser.get(section, "description")
        parser.remove_section(section)
        _say(printer, f"Removed KDE window rule: {description}")

    if parser.has_section("General"):
        remaining = [
            item.strip()
            for item in parser.get("General", "rules", fallback="").split(",")
            if item.strip() and item.strip() not in doomed
        ]
        parser.set("General", "rules", ",".join(remaining))
        parser.set("General", "count", str(len(remaining)))
    try:
        with open(rc_path, "w", encoding="utf-8") as handle:
            parser.write(handle)
    except OSError:
        return
    run(["qdbus", "org.kde.KWin", "/KWin", "reconfigure"])


def remove_motd_hook(
    home: Path,
    *,
    dry_run: bool,
    printer: Printer = print,
) -> None:
    """Remove the dynamic-MOTD block manage_motd.py appends to ~/.bashrc."""
    bashrc = home / ".bashrc"
    if not bashrc.is_file():
        return
    try:
        text = bashrc.read_text(encoding="utf-8")
    except OSError:
        return
    start = text.find(MOTD_BEGIN)
    if start < 0:
        return
    end = text.find(MOTD_END, start)
    if end < 0:
        return
    end += len(MOTD_END)
    # Swallow one blank line on either side so the edit leaves no double gap.
    if end < len(text) and text[end] == "\n":
        end += 1
    if start > 0 and text[start - 1] == "\n" and start > 1 and text[start - 2] == "\n":
        start -= 1
    if dry_run:
        _say(printer, f"Would remove the dynamic-MOTD hook from {bashrc}")
        return
    try:
        bashrc.write_text(text[:start] + text[end:], encoding="utf-8")
    except OSError:
        return
    _say(printer, f"Removed the dynamic-MOTD hook from {bashrc}")


def remove_mac_bundles(
    home: Path,
    root: Path,
    *,
    dry_run: bool,
    printer: Printer = print,
    runner: Runner | None = None,
) -> None:
    """Remove the companion app bundles and their LaunchServices records.

    Only a bundle whose CFBundleIdentifier is the companion's is touched, so a
    same-named application from somewhere else is never deleted.
    """
    run = runner or _default_runner
    candidates = [Path(str(path).replace("~", str(home), 1)) for path in MAC_BUNDLES]
    candidates.append(root / "MP Web Companion.app")
    seen: set[Path] = set()
    for bundle in candidates:
        if bundle in seen:
            continue
        seen.add(bundle)
        if not bundle.exists():
            continue
        if _bundle_identifier(bundle) != COMPANION_BUNDLE_ID:
            _say(printer, f"Kept app bundle (not the companion): {bundle}")
            continue
        if dry_run:
            _say(printer, f"Would remove app bundle: {bundle}")
            continue
        lsregister = _lsregister()
        if lsregister.is_file():
            run([str(lsregister), "-u", str(bundle)])
        _remove_path(bundle, printer, "app bundle", dry_run)

    tray_bundle = home / ".config" / "mix-manager" / "MP Mix Manager Tray.app"
    if tray_bundle.exists():
        if dry_run:
            _say(printer, f"Would remove app bundle: {tray_bundle}")
        else:
            lsregister = _lsregister()
            if lsregister.is_file():
                run([str(lsregister), "-u", str(tray_bundle)])
            _remove_path(tray_bundle, printer, "menu-bar bundle", dry_run)


def remove_windows_startup(
    home: Path,
    *,
    dry_run: bool,
    printer: Printer = print,
) -> None:
    startup = (
        home
        / "AppData"
        / "Roaming"
        / "Microsoft"
        / "Windows"
        / "Start Menu"
        / "Programs"
        / "Startup"
    )
    for name in WINDOWS_STARTUP_FILES:
        _remove_path(startup / name, printer, "Startup shortcut", dry_run)


def remove_config_integration(
    home: Path,
    *,
    dry_run: bool,
    printer: Printer = print,
) -> None:
    """Delete generated bundles and launcher stubs, never user settings."""
    config = home / ".config" / "mix-manager"
    for relative in CONFIG_INTEGRATION_PATHS:
        _remove_path(config / relative, printer, "integration", dry_run)


def remove_all(
    home: Path,
    root: Path,
    *,
    dry_run: bool = False,
    stop_running: bool = False,
    printer: Printer = print,
    runner: Runner | None = None,
) -> None:
    """Every step above, in the order that stops writers before their files.

    ``stop_running`` is off by default. Killing processes is the shell entry
    point's job, because only it knows whether the user passed ``--no-stop``;
    the file removal below is safe to run while an app is open.
    """
    home = Path(home)
    root = Path(root)
    if stop_running:
        stop_processes(dry_run=dry_run, printer=printer, runner=runner)
    remove_services(home, dry_run=dry_run, printer=printer, runner=runner)
    remove_desktop_helper(home, root, dry_run=dry_run, printer=printer)
    remove_icons(home, dry_run=dry_run, printer=printer)
    remove_config_integration(home, dry_run=dry_run, printer=printer)
    remove_mac_bundles(home, root, dry_run=dry_run, printer=printer, runner=runner)
    remove_windows_startup(home, dry_run=dry_run, printer=printer)
    remove_kwin_rules(home, dry_run=dry_run, printer=printer, runner=runner)
    remove_motd_hook(home, dry_run=dry_run, printer=printer)


def main(argv: Iterable[str] | None = None) -> int:
    import argparse

    parser = argparse.ArgumentParser(
        description="Remove the MP Mix Manager per-user OS integration."
    )
    parser.add_argument("--home", default=str(Path.home()))
    parser.add_argument("--root", default=str(Path(__file__).resolve().parent.parent))
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args(list(argv) if argv is not None else sys.argv[1:])
    remove_all(Path(args.home), Path(args.root), dry_run=args.dry_run)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
