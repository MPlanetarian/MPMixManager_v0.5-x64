"""Place fullscreen windows on specific monitors, including on Wayland.

A Wayland client cannot decide where its window goes: the compositor owns
placement, ``glfwSetWindowPos`` is ignored, and ``glfwSetWindowMonitor`` on a
non-primary monitor asserts inside libglfw. On a four-screen machine that means
a multi-monitor screen saver stacks every window on one or two displays — it
looks like the saver "doesn't load on all 4 displays".

X11 has no such restriction, so the normal move-and-fullscreen path works there
and this module is a no-op. On Wayland the window is moved by **KWin**, the only
component allowed to do it:

1. Write a small KWin script that activates the target window and calls
   ``workspace.slotWindowToNextScreen()`` until the window is on the requested
   output.
2. ``loadScript`` + ``start`` it over D-Bus, then unload it.

Everything is best effort. A missing ``qdbus``, a non-KDE desktop, or a refused
request leaves the window where the compositor put it; nothing raises, so a
screen saver never dies because placement failed.
"""
from __future__ import annotations

import os
import shutil
import subprocess
import tempfile
import time
from pathlib import Path
from typing import List, Optional

_DBUS_TIMEOUT = 4.0

# KWin acts on the ACTIVE window, so only one placement script may run at a
# time across the whole machine. Each saver window is a separate process, so
# the lock has to be a file rather than a threading primitive.
_LOCK_PATH = Path(tempfile.gettempdir()) / "mp-visualizer-placement.lock"


class _PlacementLock:
    """A cross-process lock around KWin placement."""

    def __init__(self, timeout: float = 15.0):
        self.timeout = timeout
        self._fh = None

    def __enter__(self):
        import fcntl
        deadline = time.monotonic() + self.timeout
        self._fh = open(_LOCK_PATH, "w")
        while True:
            try:
                fcntl.flock(self._fh, fcntl.LOCK_EX | fcntl.LOCK_NB)
                return self
            except OSError:
                if time.monotonic() >= deadline:
                    return self           # proceed unlocked rather than stall
                time.sleep(0.05)

    def __exit__(self, *exc):
        try:
            import fcntl
            fcntl.flock(self._fh, fcntl.LOCK_UN)
        except Exception:
            pass
        try:
            self._fh.close()
        except Exception:
            pass
        return False


def is_wayland() -> bool:
    """True when this process is talking to a Wayland compositor."""
    if os.environ.get("WAYLAND_DISPLAY"):
        return True
    return str(os.environ.get("XDG_SESSION_TYPE", "")).lower() == "wayland"


def _dbus_tool() -> Optional[str]:
    for name in ("qdbus6", "qdbus"):
        found = shutil.which(name)
        if found:
            return found
    return None


def _kwin(tool: str, path: str, interface: str, method: str, *args: str) -> str:
    try:
        result = subprocess.run(
            [tool, "org.kde.KWin", path, f"{interface}.{method}", *args],
            capture_output=True, text=True, timeout=_DBUS_TIMEOUT,
        )
        return result.stdout.strip() if result.returncode == 0 else ""
    except (OSError, subprocess.SubprocessError):
        return ""


def kwin_available() -> bool:
    """True when KWin's scripting interface can be reached over D-Bus."""
    if not is_wayland():
        return False
    tool = _dbus_tool()
    if not tool:
        return False
    # isScriptLoaded answers even for an unknown name, which proves the call
    # path works without side effects.
    out = _kwin(tool, "/Scripting", "org.kde.kwin.Scripting",
                "isScriptLoaded", "mp-placement-probe")
    return out in ("true", "false")


def _script_source(assignments, max_steps: int = 6) -> str:
    """One KWin script that places EVERY window, one at a time.

    Doing all of them in a single script is deliberate. KWin moves the *active*
    window, so four scripts started together fight over which window is active
    and several end up on the same screen. One script can await each move in
    order, which is the only reliable way to lay out a wall.
    """
    entries = []
    for title, output in assignments:
        t = str(title).replace("\\", "\\\\").replace('"', '\\"')
        o = str(output).replace("\\", "\\\\").replace('"', '\\"')
        entries.append('{ title: "%s", output: "%s" }' % (t, o))
    return """
// Generated by the MP Visualizer screen saver.
const ASSIGNMENTS = [%s];
const MAX_STEPS = %d;

function findWindow(title) {
    var ws = workspace.windowList();
    // Exact match first, then a prefix match. KWin appends the app name to
    // some captions ("...[0,0] — MP_Visualizer"), and the owner window is given
    // its caption after the script may already have started looking.
    for (var i = 0; i < ws.length; i++) {
        var cap = "";
        try { cap = String(ws[i].caption || ""); } catch (e) { continue; }
        if (cap === title) return ws[i];
    }
    for (var i = 0; i < ws.length; i++) {
        var cap2 = "";
        try { cap2 = String(ws[i].caption || ""); } catch (e) { continue; }
        if (cap2.indexOf(title) === 0) return ws[i];
    }
    return null;
}

function outputOf(w) {
    try { return w.output ? String(w.output.name) : ""; } catch (e) { return ""; }
}

function moveTo(w, target) {
    var at = outputOf(w);
    if (at === target) return true;
    // Force a real activation change. If the window is ALREADY active, KWin
    // ignores the reassignment and the screen-move slot then does nothing,
    // which is why the focused window used to stay on the wrong screen.
    try {
        var other = null;
        var ws = workspace.windowList();
        for (var i = 0; i < ws.length; i++) {
            if (ws[i] !== w) { other = ws[i]; break; }
        }
        if (other) workspace.activeWindow = other;
        workspace.activeWindow = w;
    } catch (e) { return false; }
    // KWin's slotWindowToNextScreen wraps around the output list, so walking
    // forward always reaches the target. Trace the walk so a failure is
    // diagnosable instead of silent.
    var trail = [at];
    for (var i = 0; i < MAX_STEPS * 4; i++) {
        try { workspace.slotWindowToNextScreen(); } catch (e) { break; }
        var now = outputOf(w);
        trail.push(now);
        if (now === target) {
            console.info("MPWALK " + target + " via " + trail.join(">"));
            return true;
        }
    }
    console.info("MPWALK " + target + " FAILED trail " + trail.join(">"));
    return false;
}

function run() {
    // Two passes. The first seats every window that is not already correct.
    // The second is a verification pass: moving one window can shift nothing
    // else, but a swallowed step during a busy frame can, so anything wrong
    // after pass one is corrected here.
    for (var pass = 0; pass < 2; pass++) {
        for (var i = 0; i < ASSIGNMENTS.length; i++) {
            var a = ASSIGNMENTS[i];
            var w = findWindow(a.title);
            if (!w) {
                if (pass === 0) console.info("MPPLACE missing " + a.title);
                continue;
            }
            var before = outputOf(w);
            if (before === a.output) continue;
            var ok = moveTo(w, a.output);
            if (!ok) {
                console.info("MPPLACE " + a.title + " -> " + outputOf(w) +
                             " FAILED target " + a.output);
            } else if (pass > 0) {
                console.info("MPPLACE corrected " + a.title + " from " + before);
            }
        }
    }
    // Report the final state once.
    for (var i = 0; i < ASSIGNMENTS.length; i++) {
        var a2 = ASSIGNMENTS[i];
        var w2 = findWindow(a2.title);
        console.info("MPFINAL " + a2.title + " on " +
                     (w2 ? outputOf(w2) : "missing") + " want " + a2.output);
    }
}
run();
""" % (", ".join(entries), int(max_steps))


def _run_script(tool: str, source: str) -> bool:
    """Load, start and unload one KWin script."""
    script = Path(tempfile.gettempdir()) / f"mp-place-{os.getpid()}-{len(source) % 9999}.js"
    try:
        script.write_text(source, encoding="utf-8")
    except OSError:
        return False
    # A unique plugin name per run: loadScript refuses to reload a name that is
    # already registered, which silently skipped whole walls.
    name = f"mp-place-{os.getpid()}-{int(time.time() * 1000) % 1000000}"
    loaded = _kwin(tool, "/Scripting", "org.kde.kwin.Scripting",
                   "loadScript", str(script), name)
    if not loaded:
        try:
            script.unlink(missing_ok=True)
        except OSError:
            pass
        return False
    _kwin(tool, "/Scripting", "org.kde.kwin.Scripting", "start")
    # The script walks every window in order, so allow time proportional to the
    # wall size before cleaning up.
    time.sleep(0.25 + 0.35 * max(1, source.count("title:")))
    try:
        script.unlink(missing_ok=True)
    except OSError:
        pass
    return True


def place_on_output(title: str, output: str, max_steps: int = 6) -> bool:
    """Ask KWin to move one window onto ``output``."""
    return assign([{"title": title, "output": output}], max_steps=max_steps) > 0


def assign(windows: List[dict], max_steps: int = 6) -> int:
    """Place every window in one KWin script, sequentially.

    ``windows`` is a list of ``{"title": ..., "output": ...}`` mappings. Returns
    how many assignments were requested (0 when placement is not applicable).
    """
    if not windows or not is_wayland():
        return 0
    tool = _dbus_tool()
    if not tool:
        return 0
    pairs = [
        (str(w.get("title", "")), str(w.get("output", "")))
        for w in windows
        if str(w.get("title", "")) and str(w.get("output", ""))
    ]
    if not pairs:
        return 0
    # Keep the caller's screen order. Moving them in a fixed order means each
    # walk starts from a known place instead of from whatever the previous
    # script happened to leave active.
    with _PlacementLock():
        ok = _run_script(tool, _script_source(pairs, max_steps))
    return len(pairs) if ok else 0


def output_for_rect(rect) -> str:
    """Best-effort output name for a desktop rectangle.

    KWin scripts report output *names* (``DP-1``), while the saver plans
    geometry by rect. The two are matched by asking KWin for the rect of each
    output once and caching it.
    """
    key = tuple(int(v) for v in rect[:4])
    cached = _OUTPUT_RECTS.get(key)
    if cached:
        return cached
    return ""


_OUTPUT_RECTS: dict = {}


def cache_output_rects(mapping: dict) -> None:
    """Record ``{(x, y, w, h): "DP-1"}`` so rects can be translated to names."""
    for rect, name in mapping.items():
        try:
            _OUTPUT_RECTS[tuple(int(v) for v in rect)] = str(name)
        except (TypeError, ValueError, IndexError):
            continue
