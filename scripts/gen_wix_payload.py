#!/usr/bin/env python3
"""Generate the WiX payload fragment for the staged Windows tree.

The 0.5.4 installer is a WiX 5 MSI whose Directory table puts the whole
application under ``ProgramFiles6432Folder\\MP Mix Manager``. This writes the
same shape: one ``Directory`` per subdirectory of the staged tree, one
``Component`` per file (each file is its own key path, which is what the
reference package does), and a single ``ComponentGroup`` the product includes.

The product itself (properties, upgrade rules, launch conditions, the Start
Menu shortcut) lives in ``Product.wxs``; only the harvested tree is generated
here so a rebuild never has to hand-edit hundreds of entries.
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path
from xml.sax.saxutils import escape, quoteattr

# Directory stable ids are derived from the relative path so a rebuild keeps
# the same identifiers and the MSI diffs cleanly.
DIR_ID_PREFIX = "dir"
FILE_ID_PREFIX = "fil"

# Characters WiX/Windows allow in a Directory Id.
SAFE = set("abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_")


def make_id(prefix: str, relative: str) -> str:
    """A deterministic, filesystem-safe identifier for a path.

    Windows Installer identifiers are limited to 72 characters, so a long path
    keeps a readable head and gains a short stable hash tail. The hash makes
    the id deterministic across rebuilds without ever colliding.
    """
    cleaned = "".join(ch if ch in SAFE else "_" for ch in relative)
    # Collapse runs so very long paths stay readable.
    while "__" in cleaned:
        cleaned = cleaned.replace("__", "_")
    cleaned = cleaned.strip("_")
    candidate = f"{prefix}_{cleaned}"
    if len(candidate) <= 62:
        return candidate
    digest = hashlib.sha1(relative.encode("utf-8")).hexdigest()[:8]
    head = cleaned[: 62 - len(prefix) - 10].rstrip("_")
    return f"{prefix}_{head}_{digest}"


def main() -> int:
    if len(sys.argv) < 3:
        print("usage: gen_wix_payload.py STAGE_DIR OUTPUT_WXS", file=sys.stderr)
        return 2

    stage = Path(sys.argv[1]).resolve()
    output = Path(sys.argv[2]).resolve()
    if not stage.is_dir():
        print(f"staged tree not found: {stage}", file=sys.stderr)
        return 2

    files = sorted(
        (p for p in stage.rglob("*") if p.is_file()),
        key=lambda p: str(p.relative_to(stage)).lower(),
    )

    # Group files by their parent directory (relative to the stage root).
    by_dir: dict[Path, list[Path]] = {}
    for path in files:
        by_dir.setdefault(path.parent.relative_to(stage), []).append(path)

    seen_ids: set[str] = set()
    components: list[str] = []

    def unique(candidate: str) -> str:
        if candidate not in seen_ids:
            seen_ids.add(candidate)
            return candidate
        index = 2
        while f"{candidate}_{index}" in seen_ids:
            index += 1
        final = f"{candidate}_{index}"
        seen_ids.add(final)
        return final

    lines: list[str] = []
    add = lines.append
    add('<?xml version="1.0" encoding="utf-8"?>')
    add('<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">')
    add("  <!-- Generated by scripts/gen_wix_payload.py. Do not edit by hand. -->")
    add("  <Fragment>")
    add('    <DirectoryRef Id="INSTALLFOLDER">')

    def emit_files(directory: Path, indent: str) -> None:
        for path in by_dir.get(directory, []):
            file_id = unique(make_id(FILE_ID_PREFIX, str(path.relative_to(stage))))
            component_id = unique(f"cmp_{file_id}")
            components.append(component_id)
            add(f'{indent}<Component Id="{component_id}" Guid="*">')
            add(f'{indent}  <File Id="{file_id}" KeyPath="yes" '
                f'Source={quoteattr(str(path))} Name={quoteattr(path.name)} />')
            add(f"{indent}</Component>")

    # Root-level files belong to INSTALLFOLDER itself.
    emit_files(Path("."), "      ")

    # Every directory that holds files, plus every ancestor of one, so the
    # tree is emitted nested instead of flat under INSTALLFOLDER. A flat emit
    # silently drops the intermediate folder: scripts/wix and shaders/presets
    # would install into the application root.
    needed: set[Path] = set()
    for directory in by_dir:
        if directory == Path("."):
            continue
        for depth in range(1, len(directory.parts) + 1):
            needed.add(Path(*directory.parts[:depth]))
    if not needed:
        add("    </DirectoryRef>")
        add("  </Fragment>")
    else:
        children: dict[Path, list[Path]] = {}
        for directory in needed:
            children.setdefault(directory.parent, []).append(directory)

        dir_ids: dict[Path, str] = {}

        def walk(parent: Path, indent: str) -> None:
            for directory in sorted(children.get(parent, []),
                                    key=lambda p: str(p).lower()):
                dir_id = unique(make_id(DIR_ID_PREFIX, str(directory)))
                dir_ids[directory] = dir_id
                add(f'{indent}<Directory Id="{dir_id}" '
                    f'Name={quoteattr(directory.name)}>')
                emit_files(directory, indent + "  ")
                walk(directory, indent + "  ")
                add(f"{indent}</Directory>")

        walk(Path("."), "      ")
        add("    </DirectoryRef>")
        add("  </Fragment>")

    add("")

    # The ComponentGroup that Product.wxs references.
    add("  <Fragment>")
    add('    <ComponentGroup Id="PayloadGroup">')
    for value in components:
        add(f'      <ComponentRef Id="{value}" />')
    add("    </ComponentGroup>")
    add("  </Fragment>")
    add("</Wix>")

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {output}")
    print(f"  files      : {len(files)}")
    print(f"  components : {len(components)}")
    print(f"  directories: {len(dir_ids) + 1}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
